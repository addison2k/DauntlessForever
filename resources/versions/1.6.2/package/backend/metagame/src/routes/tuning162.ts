function BountyGameData(ids: string[]){
    return {
        max_slots: 4,
        num_draft_options: 3,
        num_spicy_options: 1,
        bounty_token_id: "TOKEN_BOUNTY_DRAFT",
        premium_bounty_token_id: "TOKEN_BOUNTY_DRAFT_PREMIUM",
        num_tokens_hp_start: 4,
        num_tokens_per_day: 0,
        bounty_token_grant_hour: 0,
        history_length: 10,
        bronze_count: 9,
        silver_count: 3,
        gold_count: 1,
        new_season_reset_bounties: false,
        bounty_ids: ids,
        bounty_data: ids.map(bounty_id => ({ bounty_id, enabled: true })),
        item_grant_data: [],
        token_rollover_warning_days: 1000,
        automatic_draft: false,
        automatic_claim: false,
        delete_claimed_bounties: false,   // game server clears claimed bounties at once (false kept the card until relog)
    };
}

const BLOBS: Record<string, string[]> = {
    bounty_game_data: BOUNTY_IDS,
    bounty_game_data_daily: DAILY_CHALLENGE_IDS,
    bounty_game_data_weekly: WEEKLY_CHALLENGE_IDS,
};

for (const [BlobId, Ids] of Object.entries(BLOBS)) {
    tuning162Router.get(`/game_tuning/${BlobId}`, (req: any, res) => {
        logger.info(`Game tuning ${BlobId} (1.6.2, ${Ids.length} enabled)`);
        res.status(200);
        res.json({ code: null, message: "OK", payload: BountyGameData(Ids) });
    });
}
