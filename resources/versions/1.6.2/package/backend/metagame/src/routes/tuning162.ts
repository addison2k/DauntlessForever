// [1.6.2 port] Game-tuning blobs that 1.6.2 requests but 1.4.4 did not.
// In 1.6.2 the bounty configuration comes from the game-tuning blobs bounty_game_data,
// bounty_game_data_daily and bounty_game_data_weekly (GET /game_tuning/{blobid}),
// instead of 1.4.4's /bounty/game-data. Wrapped in {code, message, payload} like Undaunted's other /game_tuning replies.
//
// Enabled bounties: the game server resets (and refunds) any saved bounty that is "disabled from config". Undaunted's
// stub sent its list as bounty_data, a name the 1.6.2 exe does not contain, so every bounty counted as disabled and
// drafted bounties vanished on the next load. The exe does read "bounty_ids", so the enabled lists are sent there
// (bounty_data is kept too, filled the same way). Ids come from the game's own tables (FModel, Content/Gameplay/Bounty):
// bounty_table (bounty_game_data), challenge_seasons_daily_table (_daily), challenge_seasons_weekly_table (_weekly).

